export const DICT = D;
export const LANG_KEY = 'dasara.lang';
const LangCtx = createContext(null);

export function LangProvider({ children }) {
  // English first. (A new storage name, so phones that had Telugu saved by the old default start in English once.)
  const [lang, setLangState] = useState(() => localStorage.getItem(LANG_KEY) || 'en');
  const setLang = useCallback((l) => { localStorage.setItem(LANG_KEY, l); setLangState(l); document.documentElement.lang = l; }, []);
  const t = useCallback((key, vars) => {
    const e = D[key];
    let s = e ? (lang === 'te' ? e[0] : e[1]) : key;
    if (!e && import.meta.env.DEV) console.warn('missing i18n key', key);
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
    return s;
  }, [lang]);
  /** pick obj[base_te] / obj[base_en] with fallback to the other language */
  const L = useCallback((obj, base) => {
    if (!obj) return '';
    const a = obj[`${base}_${lang}`], b = obj[`${base}_${lang === 'te' ? 'en' : 'te'}`];
    return (a && String(a).trim()) ? a : (b || '');
  }, [lang]);
  /** pick {te, en} item */
  const P = useCallback((item) => (!item ? '' : (lang === 'te' ? item.te || item.en : item.en || item.te) || ''), [lang]);
  const value = useMemo(() => ({ lang, setLang, t, L, P }), [lang, setLang, t, L, P]);
  return <LangCtx.Provider value={value}>{children}</LangCtx.Provider>;
}

export const useLang = () => useContext(LangCtx);

export function LangSwitch() {
  const { lang, setLang } = useLang();
  return (
    <div className="lang-switch" role="group" aria-label="Language">
      <button type="button" className={lang === 'te' ? 'on' : ''} onClick={() => setLang('te')}>తెలుగు</button>
      <button type="button" className={lang === 'en' ? 'on' : ''} onClick={() => setLang('en')}>English</button>
    </div>
  );
}
